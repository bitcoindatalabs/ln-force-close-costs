def save(fig, name: str):
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIGURES_DIR / f"{name}.pdf")
    fig.savefig(FIGURES_DIR / f"{name}.png", dpi=200)    # preview only; the paper uses the PDF
    plt.close(fig)
    print(f"  figure {name}")


def year_axis(ax, years):
    ax.set_xticks(list(years))
    ax.set_xticklabels([str(y) for y in years])
    ax.grid(axis="x", visible=False)


def tex_table(name: str, header: list, rows: list, align: str, caption: str, label: str, note: str = "",
              wide: bool = False):
    """Write a booktabs table environment to paper/tables/<name>.tex. Cells are already-formatted strings."""
    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    env = "table*" if wide else "table"
    lines = ["% Generated by src/ -- do not edit by hand.", f"\\begin{{{env}}}[t]", "\\centering",
             f"\\caption{{{caption}}}", f"\\label{{{label}}}", "\\footnotesize",
             f"\\begin{{tabular}}{{{align}}}", "\\toprule", " & ".join(header) + " \\\\", "\\midrule"]
    for r in rows:
        lines.append("\\midrule" if r == "MIDRULE" else " & ".join(r) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    if note:
        lines.append(f"\\par\\smallskip\\parbox{{\\linewidth}}{{\\scriptsize {note}}}")
    lines.append(f"\\end{{{env}}}")
    (TABLES_DIR / f"{name}.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  table {name}")


def n(x) -> str:
    """Thousands separator for LaTeX: 12{,}345."""
    return f"{int(round(x)):,}".replace(",", "{,}")


def f1(x) -> str:
    return f"{x:.1f}"
